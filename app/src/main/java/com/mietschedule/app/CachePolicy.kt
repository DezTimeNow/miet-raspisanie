package com.mietschedule.app

/**
 * Общие числа политики кэша и фоновых задач.
 *
 * Вынесено отдельно, потому что TTL кэша и период фоновой задачи обязаны
 * совпадать: если задача просыпается реже, чем протухает кэш, приложение
 * показывало бы устаревшие данные дольше задуманного; если чаще — сеть
 * трогается без нужды.
 */
object CachePolicy {

    /**
     * Сколько живёт кэш расписания группы.
     *
     * Раньше срока не было вовсе: кэш писался один раз и жил вечно, а
     * условие загрузки `force || lessons.isEmpty()` при непустом кэше сеть
     * не дёргал. Пользователь, открывавший приложение каждый день, месяцами
     * видел расписание, изменившееся на сайте.
     *
     * Шесть часов — компромисс: расписание меняется редко, но «на неделю»
     * слишком долго, а минутный интервал бессмыслен для 343 групп.
     */
    const val SCHEDULE_TTL_MS = 6L * 60 * 60 * 1000

    /** Период фоновой актуализации. Android не выполняет задачи чаще 15 минут. */
    const val REFRESH_PERIOD_MS = 6L * 60 * 60 * 1000

    /** Список групп меняется раз в семестр — недели хватает. */
    const val GROUPS_TTL_MS = 7L * 24 * 60 * 60 * 1000
}